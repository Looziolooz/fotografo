// Process every wedding photo into (a) 4:5 grid thumbnails for the home grid and
// (b) aspect-preserved full images for the gallery pages. A thin strip is cropped
// off the bottom of each source to remove the Gemini ✦ watermark, and thumbnails
// use sharp's skin-tone-aware "attention" crop so couples stay centred.
// Emits src/content/galleries.ts.
//   node scripts/process-galleries.mjs
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const ROOT = "C:/Users/loren/Pictures/fotografo";
const OUT = "public/images/portfolio";
const WATERMARK_TRIM = 0.07; // crop 7% off the bottom (removes the corner sparkle)

const COUPLES = [
  { dir: "francesca e roberto capri", slug: "francesca-roberto", display: "Francesca & Roberto", location: "Capri, Italia" },
  { dir: "elena e davide val d orcia", slug: "elena-davide", display: "Elena & Davide", location: "Val d'Orcia, Italia" },
  { dir: "sofia e alessandro positano", slug: "sofia-alessandro-positano", display: "Sofia & Alessandro", location: "Positano, Italia" },
  { dir: "emma e luca siena", slug: "emma-luca", display: "Emma & Luca", location: "Siena, Italia" },
  { dir: "valentina e matteo ravello", slug: "valentina-matteo", display: "Valentina & Matteo", location: "Ravello, Italia" },
  { dir: "martina e federico san gimignano", slug: "martina-federico", display: "Martina & Federico", location: "San Gimignano, Italia" },
  { dir: "chiara e marco", slug: "chiara-marco", display: "Chiara & Marco", location: "Firenze, Italia" },
  { dir: "sofia e alessandro", slug: "sofia-alessandro", display: "Sofia & Alessandro", location: "Lago di Como, Italia" },
];

const imgs = (dir) => fs.readdirSync(path.join(ROOT, dir)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();

/** Source with the bottom watermark strip removed, as a buffer. */
async function deWatermark(src) {
  const m = await sharp(src).metadata();
  const height = Math.round(m.height * (1 - WATERMARK_TRIM));
  return sharp(src).extract({ left: 0, top: 0, width: m.width, height }).toBuffer();
}

const galleries = {};
const perCouple = [];

for (const c of COUPLES) {
  const dirOut = path.join(OUT, c.slug);
  fs.mkdirSync(dirOut, { recursive: true });
  const files = imgs(c.dir);
  const images = [];
  const cards = [];
  for (let i = 0; i < files.length; i++) {
    const clean = await deWatermark(path.join(ROOT, c.dir, files[i]));

    const full = `g${i + 1}.webp`;
    const m = await sharp(clean).resize(1600, 1600, { fit: "inside", withoutEnlargement: true }).webp({ quality: 82 }).toFile(path.join(dirOut, full));
    images.push({ src: `/images/portfolio/${c.slug}/${full}`, w: m.width, h: m.height });

    const th = `t${i + 1}.webp`;
    await sharp(clean).resize(880, 1100, { fit: "cover", position: "attention" }).webp({ quality: 80 }).toFile(path.join(dirOut, th));
    cards.push({ slug: c.slug, names: c.display, location: c.location, thumb: `/images/portfolio/${c.slug}/${th}` });
  }
  galleries[c.slug] = { names: c.display, location: c.location, images };
  perCouple.push(cards);
  console.log(c.slug, "->", files.length, "imgs");
}

// About portrait — tall B&W crop from the first couple's set (watermark removed).
{
  const c = COUPLES[0];
  const files = imgs(c.dir);
  const clean = await deWatermark(path.join(ROOT, c.dir, files[1] || files[0]));
  await sharp(clean).resize(1100, 1320, { fit: "cover", position: "attention" }).grayscale().webp({ quality: 82 }).toFile(path.join(OUT, "about-portrait.webp"));
}

// Interleave cards round-robin so couples alternate down the grid.
const cards = [];
for (let r = 0, added = true; added; r++) {
  added = false;
  for (const cc of perCouple) if (cc[r]) { cards.push(cc[r]); added = true; }
}

const ts = `// AUTO-GENERATED by scripts/process-galleries.mjs — do not edit by hand.
export interface GalleryImage { src: string; w: number; h: number; }
export interface GridCard { slug: string; names: string; location: string; thumb: string; }
export interface Gallery { names: string; location: string; images: GalleryImage[]; }

export const GRID_CARDS: GridCard[] = ${JSON.stringify(cards, null, 2)};

export const GALLERIES: Record<string, Gallery> = ${JSON.stringify(galleries, null, 2)};
`;
fs.writeFileSync("src/content/galleries.ts", ts);
console.log("DONE — couples:", Object.keys(galleries).length, "grid cards:", cards.length);
